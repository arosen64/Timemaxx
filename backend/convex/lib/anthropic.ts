import { createAnthropic } from "@ai-sdk/anthropic";
import { generateText, Output } from "ai";
import { z } from "zod";
import type { GenericActionCtx } from "convex/server";
import type { DataModel, Id } from "../_generated/dataModel";
import {
  estimateCostUsd,
  recordAiCall,
  type Provider,
} from "./aiObservability";

const MODEL = "claude-sonnet-4-20250514";
const PROVIDER: Provider = "anthropic";

export interface AiCallObservability {
  ctx: GenericActionCtx<DataModel>;
  callSite: string;
  userId?: Id<"users">;
  metadata?: Record<string, unknown>;
}

function isTimeoutError(err: unknown): boolean {
  return (
    err instanceof Error &&
    (err.name === "AbortError" || err.name === "TimeoutError" || err.name === "ResponseAborted")
  );
}

/**
 * Calls Anthropic Claude via the Vercel AI SDK with Zod-validated structured output.
 * Pass `obs` to log prompt/response/latency/cost to the aiCallLogs table.
 */
export async function callAnthropic<T>(opts: {
  system: string;
  prompt: string;
  schema: z.Schema<T>;
  schemaName: string;
  schemaDescription?: string;
  timeoutMs?: number;
  obs?: AiCallObservability;
}): Promise<T> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) throw new Error("ANTHROPIC_API_KEY is not set");

  const anthropic = createAnthropic({ apiKey });
  const startedAt = Date.now();

  try {
    const result = await generateText({
      model: anthropic(MODEL),
      output: Output.object({
        schema: opts.schema,
        name: opts.schemaName,
        description: opts.schemaDescription,
      }),
      system: opts.system,
      prompt: opts.prompt,
      abortSignal: opts.timeoutMs ? AbortSignal.timeout(opts.timeoutMs) : undefined,
    });

    if (result.output == null) {
      if (opts.obs) {
        await recordAiCall(opts.obs.ctx, {
          userId: opts.obs.userId,
          callSite: opts.obs.callSite,
          provider: PROVIDER,
          model: MODEL,
          status: "error",
          latencyMs: Date.now() - startedAt,
          promptPreview: `${opts.system}\n\n${opts.prompt}`,
          errorMessage: "No structured output generated by the model",
          metadata: opts.obs.metadata,
        });
      }
      throw new Error("No structured output generated by the model");
    }

    if (opts.obs) {
      const usage = (result as { usage?: { promptTokens?: number; completionTokens?: number; totalTokens?: number } }).usage;
      await recordAiCall(opts.obs.ctx, {
        userId: opts.obs.userId,
        callSite: opts.obs.callSite,
        provider: PROVIDER,
        model: MODEL,
        status: "success",
        latencyMs: Date.now() - startedAt,
        promptTokens: usage?.promptTokens,
        completionTokens: usage?.completionTokens,
        totalTokens:
          usage?.totalTokens ??
          (usage?.promptTokens !== undefined && usage?.completionTokens !== undefined
            ? usage.promptTokens + usage.completionTokens
            : undefined),
        estimatedCostUsd: estimateCostUsd(MODEL, usage?.promptTokens, usage?.completionTokens),
        promptPreview: `${opts.system}\n\n${opts.prompt}`,
        responsePreview: JSON.stringify(result.output),
        metadata: opts.obs.metadata,
      });
    }

    return result.output;
  } catch (err) {
    if (opts.obs) {
      await recordAiCall(opts.obs.ctx, {
        userId: opts.obs.userId,
        callSite: opts.obs.callSite,
        provider: PROVIDER,
        model: MODEL,
        status: isTimeoutError(err) ? "timeout" : "error",
        latencyMs: Date.now() - startedAt,
        promptPreview: `${opts.system}\n\n${opts.prompt}`,
        errorMessage: err instanceof Error ? `${err.name}: ${err.message}` : String(err),
        metadata: opts.obs.metadata,
      });
    }

    throw err;
  }
}
