import { createGoogleGenerativeAI } from "@ai-sdk/google";
import { generateText, Output } from "ai";
import { z } from "zod";
import {
  estimateCostUsd,
  recordAiCall,
  type AiCallObservability,
  type Provider,
} from "./aiObservability";

const MODEL = "gemini-2.5-flash";
const PROVIDER: Provider = "gemini";

export async function callGemini<T>(opts: {
  system: string;
  prompt: string;
  schema: z.Schema<T>;
  schemaName: string;
  schemaDescription?: string;
  timeoutMs?: number;
  obs?: AiCallObservability;
}): Promise<T> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new Error("GEMINI_API_KEY is not set");

  const google = createGoogleGenerativeAI({ apiKey });
  const startedAt = Date.now();

  try {
    const result = await generateText({
      model: google(MODEL),
      output: Output.object({
        schema: opts.schema,
        name: opts.schemaName,
        description: opts.schemaDescription,
      }),
      system: opts.system,
      prompt: opts.prompt,
      abortSignal: opts.timeoutMs ? AbortSignal.timeout(opts.timeoutMs) : undefined,
    });

    if (!result.output) {
      if (opts.obs) {
        await recordAiCall(opts.obs.ctx, {
          userId: opts.obs.userId,
          callSite: opts.obs.callSite,
          provider: PROVIDER,
          model: MODEL,
          status: "error",
          latencyMs: Date.now() - startedAt,
          promptPreview: `${opts.system}\n\n${opts.prompt}`,
          errorMessage: "No structured output generated by the model",
          metadata: opts.obs.metadata,
        });
      }
      throw new Error("No structured output generated by the model");
    }

    if (opts.obs) {
      const { inputTokens, outputTokens } = result.usage;
      await recordAiCall(opts.obs.ctx, {
        userId: opts.obs.userId,
        callSite: opts.obs.callSite,
        provider: PROVIDER,
        model: MODEL,
        status: "success",
        latencyMs: Date.now() - startedAt,
        promptTokens: inputTokens,
        completionTokens: outputTokens,
        totalTokens:
          inputTokens !== undefined && outputTokens !== undefined
            ? inputTokens + outputTokens
            : undefined,
        estimatedCostUsd: estimateCostUsd(MODEL, inputTokens, outputTokens),
        promptPreview: `${opts.system}\n\n${opts.prompt}`,
        responsePreview: JSON.stringify(result.output),
        metadata: opts.obs.metadata,
      });
    }

    return result.output;
  } catch (err) {
    const isTimeout =
      err instanceof Error && ["AbortError", "TimeoutError", "ResponseAborted"].includes(err.name);

    if (opts.obs) {
      await recordAiCall(opts.obs.ctx, {
        userId: opts.obs.userId,
        callSite: opts.obs.callSite,
        provider: PROVIDER,
        model: MODEL,
        status: isTimeout ? "timeout" : "error",
        latencyMs: Date.now() - startedAt,
        promptPreview: `${opts.system}\n\n${opts.prompt}`,
        errorMessage: err instanceof Error ? `${err.name}: ${err.message}` : String(err),
        metadata: opts.obs.metadata,
      });
    }

    throw err;
  }
}
