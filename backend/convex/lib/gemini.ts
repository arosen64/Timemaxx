import { createGoogleGenerativeAI } from "@ai-sdk/google";
import { generateText, Output } from "ai";
import { z } from "zod";

const MODEL = "gemini-2.5-flash";

/**
 * Detects timeout/abort errors from the AI SDK or Node's AbortSignal.
 * Covers DOMException (AbortError), TimeoutError, and ResponseAborted.
 */
function isTimeoutError(err: unknown): boolean {
  return (
    err instanceof Error &&
    (err.name === "AbortError" ||
      err.name === "TimeoutError" ||
      err.name === "ResponseAborted")
  );
}

/**
 * Calls Gemini via the Vercel AI SDK with Zod-validated structured output.
 *
 * - `system` and `prompt` are sent as separate roles so the model can
 *   distinguish developer instructions from user-provided content.
 * - The Zod `schema` is enforced at runtime — the returned object is
 *   guaranteed to match the schema or the call throws.
 * - Timeouts surface a clear, user-friendly error message.
 */
export async function callGemini<T>(opts: {
  system: string;
  prompt: string;
  schema: z.Schema<T>;
  schemaName: string;
  schemaDescription?: string;
  timeoutMs?: number;
}): Promise<T> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new Error("GEMINI_API_KEY is not set");

  const google = createGoogleGenerativeAI({ apiKey });

  try {
    const result = await generateText({
      model: google(MODEL),
      output: Output.object({
        schema: opts.schema,
        name: opts.schemaName,
        description: opts.schemaDescription,
      }),
      system: opts.system,
      prompt: opts.prompt,
      abortSignal: opts.timeoutMs
        ? AbortSignal.timeout(opts.timeoutMs)
        : undefined,
    });

    if (result.output == null) {
      throw new Error("No structured output generated by the model");
    }

    return result.output;
  } catch (err) {
    if (isTimeoutError(err)) {
      throw new Error("AI generation timed out — please try again");
    }
    throw err;
  }
}
